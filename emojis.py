def e(key: str) -> str:
    """Эмодзи для текста сообщения (HTML)."""
    eid, fb = EMOJI.get(key, ("", "•"))
    if eid:
        return f'<tg-emoji emoji-id="{eid}">{escape(fb)}</tg-emoji>'
    return fb


def fb(key: str) -> str:
    """Обычный эмодзи — для кнопок и всплывающих уведомлений."""
    return EMOJI.get(key, ("", "•"))[1]


def eid(key: str):
    """ID эмодзи для иконки кнопки (или None)."""
    return EMOJI.get(key, ("", ""))[0] or None
